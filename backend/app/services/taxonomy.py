# ── Title templates ─────────────────────────────────────────────────────────
# The catalog factory formats a product title from these. Slots available:
#   {brand} {series} {descriptor} {noun} {variant} {color}
# Keyed by subcategory key; "_DEFAULT" applies to everything unlisted.
# Books need "The Last Monsoon", not "Penguin The Last Monsoon Book".
TITLE_TEMPLATES: Dict[str, str] = {
    "_DEFAULT": "{brand} {series} {descriptor}",
    "fiction": "{series} {descriptor}",
    "non_fiction": "{series} {descriptor}",
    "childrens_books": "{series} {descriptor}",
    "academic": "{brand} {series} {descriptor}",
}


def title_template_for(subcat_key: str) -> str:
    return TITLE_TEMPLATES.get(subcat_key, TITLE_TEMPLATES["_DEFAULT"])


