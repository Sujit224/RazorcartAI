def validate() -> None:
    """
    Fail loudly on taxonomy mistakes at import time rather than mid-seed.
    Cheap enough to run unconditionally.
    """
    seen: set = set()
    for s in SUBCATEGORIES:
        k = s["key"]
        if k in seen:
            raise ValueError(f"[taxonomy] duplicate subcategory key: {k}")
        seen.add(k)

        if s["department"] not in RETURN_POLICIES:
            raise ValueError(
                f"[taxonomy] {k}: department {s['department']!r} has no return policy"
            )
        lo, hi = s["price"]
        if not (0 < lo < hi):
            raise ValueError(f"[taxonomy] {k}: bad price band {s['price']}")
        if s["variant_type"] != "none" and not s["variants"]:
            raise ValueError(
                f"[taxonomy] {k}: variant_type={s['variant_type']!r} but no variants listed"
            )
        if not s["brands"]:
            raise ValueError(f"[taxonomy] {k}: empty brand pool")
        if not s["image_queries"] or not s["image_nouns"]:
            raise ValueError(f"[taxonomy] {k}: image_queries/image_nouns required")
        if not s["descriptors"]:
            raise ValueError(f"[taxonomy] {k}: descriptors required for title generation")

    missing = set(DEPARTMENTS) - set(BY_DEPARTMENT)
    if missing:
        raise ValueError(f"[taxonomy] departments with no subcategories: {sorted(missing)}")

    unknown_overrides = set(POLICY_OVERRIDES) - seen
    if unknown_overrides:
        raise ValueError(
            f"[taxonomy] POLICY_OVERRIDES keys match no subcategory: {sorted(unknown_overrides)}"
        )


validate()


