def S(
    key: str,
    department: str,
    category: str,
    noun: str,
    *,
    brands: Sequence[str],
    price: Tuple[int, int],
    variant_type: str = "none",
    variants: Sequence[str] = (),
    colors: Optional[Sequence[str]] = None,
    materials: Sequence[str] = (),
    specs_t: Optional[Dict[str, Sequence[str]]] = None,
    specs_f: Optional[Dict[str, Sequence[str]]] = None,
    occasions: Sequence[str] = (),
    series: Sequence[str] = (),
    descriptors: Sequence[str] = (),
    image_queries: Sequence[str] = (),
    image_nouns: Sequence[str] = (),
    clip_prompt: Optional[str] = None,
    tags: Sequence[str] = (),
    genders: Sequence[str] = ("Unisex",),
    care: str = "none",
    origin: str = "India",
    name: Optional[str] = None,
) -> dict:
    """Build one subcategory definition, filling sensible defaults."""
    return {
        "key": key,
        "name": name or category,
        "department": department,
        "category": category,
        "noun": noun,
        "brands": list(brands),                      # ordered PREMIUM -> BUDGET
        "price": price,
        "variant_type": variant_type,
        "variants": list(variants),
        "colors": list(colors if colors is not None else NEUTRAL_COLORS),
        "materials": list(materials),
        "specs_t": {k: list(v) for k, v in (specs_t or {}).items()},   # ordered cheap -> premium
        "specs_f": {k: list(v) for k, v in (specs_f or {}).items()},   # unordered
        "occasions": list(occasions),
        "series": list(series),
        "descriptors": list(descriptors),
        "image_queries": list(image_queries or [noun.lower()]),
        "image_nouns": list(image_nouns or [noun.lower().split()[-1]]),
        "clip_prompt": clip_prompt or f"a product photo of a {noun.lower()}",
        "tags": list(tags),
        "genders": list(genders),
        "care": INDIAN_CARE[care],
        "origin": origin,
    }


