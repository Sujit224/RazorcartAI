"""
RazorCartAI Catalog Taxonomy
═════════════════════════════════════════════════════════════════════════════
Pure data. No I/O, no DB, no model loading — importable from anywhere.

Three things live here:

  1. DEPARTMENTS      — the 12 top-level store departments.
  2. RETURN_POLICIES  — per-department returnability / window / warranty matrix,
                        overridable per subcategory.  This is what lets an AI
                        buyer ask "can I return this?" and get a real answer
                        that genuinely differs by department.
  3. SUBCATEGORIES    — ~95 subcategory definitions driving BOTH the image
                        harvest (image_queries / image_nouns / clip_prompt) and
                        the catalog generator (brands / price / specs / variants).

Conventions that the catalog factory relies on:

  * `brands` is ordered PREMIUM → BUDGET.  The factory maps a brand's index to
    a price tier, so a premium brand lands high in the price band and a budget
    brand lands low.  Brand ↔ price correlation comes free from the ordering.

  * `specs_t` ("tiered") values are ordered CHEAP → PREMIUM.  The factory picks
    an index from the product's price percentile within its band, so a Rs 9k
    phone gets 4 GB RAM and a Rs 90k phone gets 16 GB.  No uniform-random
    nonsense like a budget phone with a flagship chipset.

  * `specs_f` ("free") values are unordered — picked uniformly at random.

  * `category` is the mid-level value written to the existing `Product.category`
    column.  The 7 legacy fashion values (Footwear, Topwear, Bottomwear,
    Accessories, Dresses, Ethnic Wear, Sportswear) are preserved exactly so
    products 1-70 and the existing filter UI keep working.  `department` is the
    new axis that sits above `category`.
"""

